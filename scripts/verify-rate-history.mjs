import "./test-typescript.mjs";
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync } from "node:fs";
import path from "node:path";

const output=path.resolve(".test-results");
mkdirSync(output,{recursive:true});
process.env.LMM_DATA_DIR=mkdtempSync(path.join(output,"rate-history-"));
const {getEstimatingSettings,getEstimatingProfiles,selectEstimatingProfile,saveEstimatingSettings,shopDate,getRateHistory,suggestOperations,applyOperations}=await import("../apps/web/lib/estimating.ts");
const {effectiveRate}=await import("../apps/web/lib/estimating-types.ts");
const {getQuoteVersion,createQuote,updateQuote}=await import("../apps/web/lib/quotes.ts");
const {getQuoteReview,changeWorkflow,getApprovedPackage}=await import("../apps/web/lib/workflow.ts");

const today=shopDate();
const future=shopDate(new Date(Date.now()+7*86400000));
const initial=getEstimatingSettings();
const quote=createQuote({jobName:"Rate provenance test",customer:"Fixture customer",notes:"",marginPercent:25,
  items:[{id:"part",description:"Bracket",quantity:10,costRows:[]}]});
const first=suggestOperations(quote.id,"part","plate-fab");
const apply=(s)=>applyOperations(quote.id,{...s,itemId:"part",templateId:"plate-fab"});
const original=apply(first);
assert.equal(original.items[0].costRows[0].estimate.rateSource,"Demo rate book");
const real=structuredClone(initial);
real.demo=false;
for(const rate of real.rates) rate.source="Nick’s approved shop sheet";
const stock=real.rates.find(rate=>rate.id==="plate-stock");
Object.assign(stock,{value:11.5,source:"Steel supplier · Q-208",effectiveOn:today});
const current=saveEstimatingSettings(real);
let s=suggestOperations(quote.id,"part","plate-fab");
assert.equal(s.rows[0].rate,11.5);
assert.equal(s.rows[0].estimate.rateSource,"Steel supplier · Q-208");
assert.equal(s.rows[0].estimate.rateSettingsVersion,current.version);
const next=structuredClone(current);
Object.assign(next.rates[0],{value:13.75,effectiveOn:future,source:"Steel supplier · renewal"});
const futureVersion=saveEstimatingSettings(next);
assert.throws(()=>apply(s),/rate book/);
s=suggestOperations(quote.id,"part","plate-fab");
assert.equal(s.settingsVersion,futureVersion.version);
assert.equal(s.rows[0].rate,11.5);
assert.equal(s.rows[0].estimate.rateSettingsVersion,current.version);
assert.equal(s.rows[0].estimate.rateEffectiveOn,today);
assert.equal(effectiveRate(getRateHistory(),"plate-stock",false,future).value,13.75);
const saved=apply(s);
assert.equal(getQuoteVersion(quote.id,original.version).items[0].costRows[0].rate,8);
assert.equal(saved.items[0].costRows[0].estimate.rateSource,"Steel supplier · Q-208");
assert.throws(()=>apply({...s,quoteVersion:saved.version,pricingDate:"2000-01-01"}),/rate book/);
const invalid=structuredClone(futureVersion);
invalid.rates[0].effectiveOn="2027-02-30";
assert.throws(()=>saveEstimatingSettings(invalid),/valid effective date/);

const discounted=updateQuote(quote.id,{...saved,marginPercent:15});
let review=getQuoteReview(quote.id);
assert.ok(review.pricingReasonRequired);
const details={...review.snapshot.details,scope:"Ten brackets",scopeConfirmed:true,leadTime:"Five days",leadTimeConfirmed:true,terms:"Net 30"};
const submission={version:discounted.version,action:"submit",drawingId:null};
await assert.rejects(changeWorkflow(quote.id,{...submission,details}),/reason for this pricing decision/);
details.pricingDecision={kind:"one_time",reason:"Stock on hand from this customer's prior run."};
review=await changeWorkflow(quote.id,{...submission,details});
await changeWorkflow(quote.id,{version:review.currentVersion,action:"approve",drawingId:null});
const approved=getApprovedPackage(quote.id,review.currentVersion);
assert.deepEqual(approved.approval.details.pricingDecision,details.pricingDecision);
assert.ok(!JSON.stringify(approved.customer).includes("Stock on hand"));
assert.equal(getQuoteVersion(quote.id,original.version).marginPercent,25);
let profiles=getEstimatingProfiles();
assert.equal(profiles.active,"shop");
assert.ok(profiles.practice.rates.length>=100);
const practiceTig=profiles.practice.rates.find(rate=>rate.id==="us-tig-al");
assert.equal(practiceTig.value,100);
assert.ok(profiles.practice.templates.every(template=>template.operations.every(op=>profiles.practice.rates.some(rate=>rate.id===op.rateId))));
const practiceChange={...profiles.practice,rates:profiles.practice.rates.map(rate=>rate.id===practiceTig.id?{...rate,value:104}:rate)};
saveEstimatingSettings(practiceChange,true);
profiles=getEstimatingProfiles();
assert.equal(profiles.active,"shop");
assert.equal(profiles.shop.rates.find(rate=>rate.id==="plate-stock").value,13.75);
assert.equal(profiles.practice.rates.find(rate=>rate.id===practiceTig.id).value,104);
profiles=selectEstimatingProfile({profile:"practice",version:profiles.practice.version});
assert.equal(suggestOperations(quote.id,"part","plate-fab").rows[0].rate,8);
assert.throws(()=>selectEstimatingProfile({profile:"shop",version:initial.version}),/rate book changed/);
profiles=selectEstimatingProfile({profile:"shop",version:profiles.practice.version});
assert.equal(suggestOperations(quote.id,"part","plate-fab").rows[0].rate,11.5);
assert.deepEqual(getApprovedPackage(quote.id,review.currentVersion).pdf,approved.pdf);

console.log("Verified independent practice/shop profiles, switching, dated rates, stale writes and immutable approved prices.");
